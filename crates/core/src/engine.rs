#[derive(Debug, Clone, PartialEq, Eq)]
pub enum InputEvent {
    Text(String),
    /// A normalized key press. Backends should emit this before any text
    /// event generated by the same physical key.
    Key(KeyChord),
    Backspace,
    EndOfInput,
    Delimiter(char),
    Reset,
    /// Changes capture policy for the focused surface. Sensitive fields must
    /// disable matching and clear any text already buffered. This is a
    /// compositor/backend signal, not a user action (use `PauseChanged` for that).
    FocusChanged {
        sensitive: bool,
    },
    /// User-initiated pause/resume of text expansion. Independent from
    /// `FocusChanged`: both conditions disable capture when active.
    /// Resuming does not re-enable capture if still in a sensitive field.
    PauseChanged(bool),
    /// Reports which application is now focused, for `app_filter`-scoped
    /// expansions. `None` means unknown (no window tracker running, or the
    /// compositor does not support one) -- app-restricted expansions fail
    /// closed in that case rather than matching everywhere.
    WindowChanged(Option<WindowContext>),
}

/// The focused window's identity, as reported by a window tracker backend.
/// Both fields are best-effort and compositor-dependent: a toplevel may
/// expose an app id but not a title, or vice versa.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct WindowContext {
    pub app_id: Option<String>,
    pub title: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExpansionResult {
    pub trigger: String,
    /// The exact characters that were matched in the input. This can differ
    /// from `trigger` when case propagation registered a Unicode case variant
    /// (for example, configured `ß` matched the typed text `SS`). Deletion
    /// must always use this value, never the configured trigger's length.
    pub matched_text: String,
    pub insert: String,
    /// Characters to move the cursor left after `insert` is typed, from a
    /// `{{cursor}}` marker in the replacement. `None`/`Some(0)` leave the
    /// cursor at the end, matching every replacement written before this
    /// existed.
    pub cursor_offset: Option<usize>,
    /// Character to preserve after the replacement. Evdev capture is
    /// non-exclusive, so the key that completes a word-boundary trigger or a
    /// trigger that is a prefix of another (e.g., `:a` vs `:address`) has
    /// already reached the app by the time the engine matches. Normally we
    /// delete it together with the trigger and append it to the replacement
    /// in one backend operation (`:sig ` becomes `signature `). This field is
    /// `None` for matches that complete immediately without a trailing key.
    pub reinsert_after: Option<char>,
    /// Explicit provenance: true if this expansion's replacement came from
    /// executing a command. Used for audit logging to distinguish command output
    /// from template-based expansions. No heuristics—this is set explicitly
    /// when the engine processes the command result.
    pub command_backed: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HotkeyResult {
    pub chord: KeyChord,
    pub description: String,
    pub command: CommandConfig,
}

#[derive(Debug, thiserror::Error)]
pub enum ExpansionError {
    #[error("injection failed: {0}")]
    Injection(#[from] crate::InjectorError),
}

#[derive(Debug, thiserror::Error)]
pub enum HotkeyError {
    #[error("could not start hotkey action")]
    Spawn(#[source] std::io::Error),
    #[error("hotkey action timed out after {0} ms")]
    Timeout(u64),
    #[error("hotkey action failed with status {0}")]
    Failed(String),
    #[error("hotkey action queue is full")]
    QueueFull,
    #[error("hotkey action worker is unavailable")]
    WorkerUnavailable,
}

/// Runtime counters for command-backed expansions and hotkey actions.
/// Counters are monotonically increasing for the lifetime of an engine;
/// `command_queue_depth` is the current number of jobs waiting for the worker.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct CommandMetrics {
    pub command_queue_depth: usize,
    pub command_queue_rejected_total: u64,
    pub command_timeout_total: u64,
    pub command_failure_total: u64,
}

pub struct ExpansionEngine {
    config: Config,
    matcher: Matcher,
    matcher_indices: Vec<usize>,
    buffer: VecDeque<char>,
    max_buffer_chars: usize,
    /// Set whenever the buffer evicts a character from the front because it
    /// exceeded `max_buffer_chars`, and cleared only by `buffer.clear()`
    /// (a known boundary, e.g. after a match). Lets `match_allowed`
    /// distinguish "truly at the start of input" from "a preceding
    /// character existed but was evicted" -- the two cases an empty
    /// `rev().nth(length)` cannot tell apart on its own.
    buffer_truncated: bool,
    /// User-initiated pause state. Independent from sensitive field detection.
    user_paused: bool,
    /// Compositor/backend signal that focused field is sensitive (password,
    /// OTP, etc.). Independent from user_paused.
    sensitive_focus: bool,
    command_cache: Vec<Option<CommandCacheEntry>>,
    hotkeys: Vec<(KeyChord, usize)>,
    current_window: Option<WindowContext>,
    undo_chord: Option<KeyChord>,
    /// The most recent successful expansion, kept only until the very next
    /// event of any other kind (see `process`): `(text to type back,
    /// exact text to erase)`. Not set for a result with a `{{cursor}}`
    /// marker, since undoing after the user has typed more text at that
    /// repositioned cursor has no single well-defined "erase N characters
    /// backward" meaning.
    last_expansion: Option<(String, String)>,
    input_generation: u64,
    async_commands: Option<AsyncCommandRuntime>,
    command_metrics: Arc<CommandMetricsState>,
    /// Whether a terminating character should be included in the replacement
    /// operation. Exclusive input sources have not delivered the delimiter to
    /// the application yet; non-exclusive sources such as evdev have.
    reinsert_terminators: bool,
}

#[derive(Debug, Clone)]
struct CommandCacheEntry {
    expires_at: Instant,
    value: String,
}

struct AsyncCommandRuntime {
    command_sender: mpsc::SyncSender<AsyncCommandJob>,
    hotkey_sender: mpsc::SyncSender<HotkeyResult>,
    receiver: mpsc::Receiver<AsyncCommandCompletion>,
    hotkey_receiver: mpsc::Receiver<AsyncHotkeyCompletion>,
    metrics: Arc<CommandMetricsState>,
}

struct CommandMetricsState {
    queue_depth: AtomicUsize,
    queue_rejected_total: AtomicU64,
    timeout_total: AtomicU64,
    failure_total: AtomicU64,
}

impl CommandMetricsState {
    fn new() -> Self {
        Self {
            queue_depth: AtomicUsize::new(0),
            queue_rejected_total: AtomicU64::new(0),
            timeout_total: AtomicU64::new(0),
            failure_total: AtomicU64::new(0),
        }
    }

    fn snapshot(&self) -> CommandMetrics {
        CommandMetrics {
            command_queue_depth: self.queue_depth.load(Ordering::Relaxed),
            command_queue_rejected_total: self.queue_rejected_total.load(Ordering::Relaxed),
            command_timeout_total: self.timeout_total.load(Ordering::Relaxed),
            command_failure_total: self.failure_total.load(Ordering::Relaxed),
        }
    }

    fn record_error(&self, timeout: bool) {
        if timeout {
            self.timeout_total.fetch_add(1, Ordering::Relaxed);
        } else {
            self.failure_total.fetch_add(1, Ordering::Relaxed);
        }
    }
}

impl AsyncCommandRuntime {
    fn try_send_command(&self, job: AsyncCommandJob) -> Result<(), QueueSendError> {
        self.try_send(&self.command_sender, job)
    }

    fn try_send_hotkey(&self, action: HotkeyResult) -> Result<(), QueueSendError> {
        self.try_send(&self.hotkey_sender, action)
    }

    fn try_send<T>(&self, sender: &mpsc::SyncSender<T>, job: T) -> Result<(), QueueSendError> {
        self.metrics.queue_depth.fetch_add(1, Ordering::Relaxed);
        match sender.try_send(job) {
            Ok(()) => Ok(()),
            Err(mpsc::TrySendError::Full(_)) => {
                self.metrics.queue_depth.fetch_sub(1, Ordering::Relaxed);
                self.metrics
                    .queue_rejected_total
                    .fetch_add(1, Ordering::Relaxed);
                Err(QueueSendError::Full)
            }
            Err(mpsc::TrySendError::Disconnected(_)) => {
                self.metrics.queue_depth.fetch_sub(1, Ordering::Relaxed);
                self.metrics
                    .queue_rejected_total
                    .fetch_add(1, Ordering::Relaxed);
                Err(QueueSendError::Disconnected)
            }
        }
    }
}

enum QueueSendError {
    Full,
    Disconnected,
}

enum AsyncCommandJob {
    Expansion {
        config_index: usize,
        generation: u64,
        command: CommandConfig,
        result: ExpansionResult,
    },
}

struct AsyncCommandCompletion {
    config_index: usize,
    generation: u64,
    cache_ms: u64,
    result: ExpansionResult,
    output: Result<String, CommandError>,
}

struct AsyncHotkeyCompletion {
    action: HotkeyResult,
    output: Result<(), HotkeyError>,
}

impl ExpansionEngine {
    pub fn new(config: Config) -> Result<Self, ConfigError> {
        config.validate()?;
        // Triggers match literally (see `Matcher`, a case-sensitive char
        // trie), so a `propagate_case` expansion is matched by inserting
        // its uppercase and capitalized forms as additional trigger
        // strings mapped to the same config entry, rather than by making
        // matching itself case-insensitive (which would affect every
        // expansion, not just ones that opted in). `take_match` later reads
        // back which form was actually typed to decide how to case the
        // replacement. `effective_triggers()` is the single source of
        // truth for this expansion -- `validate()` (called just above)
        // checks collisions across the exact same variants, so a config
        // that reaches this point is already known not to have two
        // expansions competing for the same matcher entry.
        let enabled: Vec<(usize, String)> = config
            .expansion
            .iter()
            .enumerate()
            .filter(|(_, entry)| entry.enabled)
            .flat_map(|(index, entry)| {
                entry
                    .effective_triggers()
                    .into_iter()
                    .map(move |trigger| (index, trigger))
            })
            .collect();
        let matcher_indices = enabled.iter().map(|(index, _)| *index).collect();
        let matcher = Matcher::new(enabled.into_iter().map(|(_, trigger)| trigger));
        let max_buffer_chars = config.settings.max_buffer_chars;
        // `validate()` above already confirmed this parses; a config that
        // fails to load is never used to construct an engine.
        let undo_chord = config
            .settings
            .undo_chord
            .as_deref()
            .and_then(|chord| KeyChord::parse(chord).ok());
        let command_cache = vec![None; config.expansion.len()];
        let hotkeys = config
            .hotkey
            .iter()
            .enumerate()
            .filter(|(_, binding)| binding.enabled)
            .filter_map(|(index, binding)| {
                KeyChord::parse(&binding.chord)
                    .ok()
                    .map(|chord| (chord, index))
            })
            .collect();
        Ok(Self {
            config,
            matcher,
            matcher_indices,
            buffer: VecDeque::new(),
            max_buffer_chars,
            buffer_truncated: false,
            user_paused: false,
            sensitive_focus: false,
            command_cache,
            hotkeys,
            current_window: None,
            undo_chord,
            last_expansion: None,
            input_generation: 0,
            async_commands: None,
            command_metrics: Arc::new(CommandMetricsState::new()),
            reinsert_terminators: true,
        })
    }

    /// Configure whether delimiters reported with a match must be reinserted.
    /// Exclusive sources need this enabled; non-exclusive sources (evdev)
    /// should leave the physical delimiter to the focused application.
    pub fn set_reinsert_terminators(&mut self, enabled: bool) {
        self.reinsert_terminators = enabled;
    }

    pub fn reinserts_terminators(&self) -> bool {
        self.reinsert_terminators
    }

    /// Run command-backed expansions and hotkey actions on separate bounded
    /// worker queues. A slow expansion command cannot delay an urgent hotkey.
    /// This is enabled by the daemon; CLI and GUI previews remain synchronous
    /// so an explicit preview call can return its result directly.
    pub fn enable_async_commands(&mut self) {
        if self.async_commands.is_some() {
            return;
        }
        let (command_sender, command_receiver) =
            mpsc::sync_channel::<AsyncCommandJob>(ASYNC_COMMAND_QUEUE_CAPACITY);
        let (hotkey_sender, hotkey_receiver) =
            mpsc::sync_channel::<HotkeyResult>(ASYNC_COMMAND_QUEUE_CAPACITY);
        let (completion_sender, completion_receiver) =
            mpsc::sync_channel(ASYNC_COMMAND_QUEUE_CAPACITY);
        let (hotkey_completion_sender, hotkey_completion_receiver) =
            mpsc::sync_channel(ASYNC_COMMAND_QUEUE_CAPACITY);
        let metrics = Arc::clone(&self.command_metrics);
        let worker_metrics = Arc::clone(&metrics);
        thread::Builder::new()
            .name("wayexpand-expansion-worker".into())
            .spawn(move || {
                while let Ok(job) = command_receiver.recv() {
                    worker_metrics.queue_depth.fetch_sub(1, Ordering::Relaxed);
                    let AsyncCommandJob::Expansion {
                        config_index,
                        generation,
                        command,
                        result,
                    } = job;
                    let cache_ms = command.cache_ms;
                    let output = run_command(&command);
                    if let Err(error) = &output {
                        worker_metrics.record_error(matches!(error, CommandError::Timeout));
                    }
                    if completion_sender
                        .send(AsyncCommandCompletion {
                            config_index,
                            generation,
                            cache_ms,
                            result,
                            output,
                        })
                        .is_err()
                    {
                        break;
                    }
                }
            })
            .expect("command worker thread should start");
        let hotkey_metrics = Arc::clone(&metrics);
        thread::Builder::new()
            .name("wayexpand-hotkey-worker".into())
            .spawn(move || {
                while let Ok(action) = hotkey_receiver.recv() {
                    hotkey_metrics.queue_depth.fetch_sub(1, Ordering::Relaxed);
                    let output = Self::execute_hotkey(&action);
                    if let Err(error) = &output {
                        hotkey_metrics.record_error(matches!(error, HotkeyError::Timeout(_)));
                    }
                    if hotkey_completion_sender
                        .send(AsyncHotkeyCompletion { action, output })
                        .is_err()
                    {
                        break;
                    }
                }
            })
            .expect("hotkey worker thread should start");
        self.async_commands = Some(AsyncCommandRuntime {
            command_sender,
            hotkey_sender,
            receiver: completion_receiver,
            hotkey_receiver: hotkey_completion_receiver,
            metrics,
        });
    }

    pub fn async_commands_enabled(&self) -> bool {
        self.async_commands.is_some()
    }

    /// Snapshot command execution counters for diagnostics and status output.
    pub fn command_metrics(&self) -> CommandMetrics {
        self.command_metrics.snapshot()
    }

    /// Applies the administrator's command-execution decision before command
    /// jobs are queued. This is separate from the config-owned organization
    /// policy because the daemon also loads `/etc/wayexpand/policy.toml`.
    pub fn set_commands_disabled(&mut self, disabled: bool) {
        self.config.organization.disable_commands = disabled;
    }

    pub fn commands_disabled(&self) -> bool {
        self.config.organization.disable_commands
    }

    pub fn set_title_matching_disabled(&mut self, disabled: bool) {
        self.config.organization.disable_title_matching = disabled;
    }

    pub fn title_matching_disabled(&self) -> bool {
        self.config.organization.disable_title_matching
    }

    /// Return completed command expansions that are still safe to apply.
    /// Any intervening input, focus, pause, or window event advances the
    /// generation and causes late output to be discarded rather than erasing
    /// text at a cursor that may have moved.
    pub fn drain_completed_commands(&mut self) -> Vec<ExpansionResult> {
        let Some(runtime) = self.async_commands.as_ref() else {
            return Vec::new();
        };
        let completions: Vec<_> = runtime.receiver.try_iter().collect();
        let mut results = Vec::new();
        for mut completion in completions {
            let Ok(mut output) = completion.output else {
                continue;
            };
            if completion.cache_ms > 0 {
                self.command_cache[completion.config_index] = Some(CommandCacheEntry {
                    expires_at: Instant::now() + Duration::from_millis(completion.cache_ms),
                    value: output.clone(),
                });
            }
            if self.config.expansion[completion.config_index].propagate_case {
                output = apply_case_style(&completion.result.matched_text, &output);
            }
            if completion.generation != self.input_generation || !self.is_capture_enabled() {
                continue;
            }
            completion.result.insert = output;
            self.last_expansion = Some((
                completion.result.matched_text.clone(),
                completion.result.insert.clone(),
            ));
            results.push(completion.result);
        }
        results
    }

    /// Queue a hotkey action for bounded asynchronous execution. The caller
    /// must drain completions periodically; neither enqueueing nor draining
    /// waits for the child process.
    pub fn queue_hotkey(&self, action: &HotkeyResult) -> Result<(), HotkeyError> {
        let Some(runtime) = self.async_commands.as_ref() else {
            return Err(HotkeyError::WorkerUnavailable);
        };
        runtime
            .try_send_hotkey(action.clone())
            .map_err(|error| match error {
                QueueSendError::Full => HotkeyError::QueueFull,
                QueueSendError::Disconnected => HotkeyError::WorkerUnavailable,
            })
    }

    /// Return hotkey action completions without waiting for any child
    /// process. Results are intended for logging and operational status; the
    /// action itself has already completed on the worker thread.
    pub fn drain_completed_hotkeys(&mut self) -> Vec<(HotkeyResult, Result<(), HotkeyError>)> {
        let Some(runtime) = self.async_commands.as_ref() else {
            return Vec::new();
        };
        runtime
            .hotkey_receiver
            .try_iter()
            .map(|completion| (completion.action, completion.output))
            .collect()
    }

    /// The currently known focused window, if any. Used to carry window
    /// context across a config reload: reload replaces the whole engine
    /// (parse-then-swap), which would otherwise silently forget the last
    /// known window until the next real focus change -- wrongly
    /// fail-closing `app_filter`-scoped expansions for a window the user
    /// never actually left.
    pub fn current_window(&self) -> Option<&WindowContext> {
        self.current_window.as_ref()
    }

    /// Restores window context captured via `current_window` before this
    /// engine replaced a previous one. Does not clear the match buffer,
    /// matching `InputEvent::WindowChanged`'s own behavior (see its
    /// handler for why that clear is unnecessary).
    pub fn set_current_window(&mut self, window: Option<WindowContext>) {
        self.current_window = window;
    }

    /// Returns whether the user has manually paused text expansion.
    /// This must be preserved across config reloads to maintain pause state.
    pub fn is_user_paused(&self) -> bool {
        self.user_paused
    }

    /// Restores user pause state from a previous engine instance.
    /// Critical for config reloads to preserve pause state.
    pub fn set_user_paused(&mut self, paused: bool) {
        self.user_paused = paused;
    }

    /// Returns whether the focused field is sensitive (password, OTP, etc).
    /// This must be preserved across config reloads to maintain input protection.
    pub fn is_sensitive_focus(&self) -> bool {
        self.sensitive_focus
    }

    /// Restores sensitive field focus state from a previous engine instance.
    /// Critical for config reloads to preserve password-field protection.
    pub fn set_sensitive_focus(&mut self, sensitive: bool) {
        self.sensitive_focus = sensitive;
    }

    /// Whether text expansion capture is currently enabled.
    /// Both user pause and sensitive field focus independently disable capture.
    fn is_capture_enabled(&self) -> bool {
        !self.user_paused && !self.sensitive_focus
    }

    /// Resolve a normalized key chord into configured actions. This method is
    /// side-effect free; the daemon or script runtime owns execution policy,
    /// cancellation, and capability checks.
    pub fn process_key(&self, chord: &KeyChord) -> Vec<HotkeyResult> {
        if !self.is_capture_enabled() {
            return Vec::new();
        }
        self.hotkeys
            .iter()
            .filter(|(configured, _)| configured.matches(chord))
            .filter_map(|(_, index)| {
                let binding: &HotkeyConfig = self.config.hotkey.get(*index)?;
                Some(HotkeyResult {
                    chord: chord.clone(),
                    description: binding.description.clone(),
                    command: binding.command.clone(),
                })
            })
            .collect()
    }

    /// If `chord` matches the configured `settings.undo_chord` and an
    /// undoable expansion is still pending (see `last_expansion`), consumes
    /// it and returns the `ExpansionResult` that reverts it: erase what was
    /// inserted, type the original trigger back. The caller applies this
    /// exactly like a normal expansion (`ExpansionEngine::apply`). Returns
    /// `None` if undo is unconfigured, paused, the chord doesn't match, or
    /// nothing is pending to undo.
    pub fn try_undo(&mut self, chord: &KeyChord) -> Option<ExpansionResult> {
        if !self.is_capture_enabled() {
            return None;
        }
        if !self.undo_chord.as_ref()?.matches(chord) {
            return None;
        }
        let (restore_text, erase_text) = self.last_expansion.take()?;
        Some(ExpansionResult {
            trigger: String::new(),
            matched_text: erase_text.clone(),
            insert: restore_text,
            cursor_offset: None,
            reinsert_after: None,
            command_backed: false,
        })
    }

    /// Execute one validated hotkey action without invoking a shell. Output
    /// is discarded and the process is bounded by the configured timeout.
    /// This is intentionally synchronous for explicit, user-initiated
    /// callers; the daemon must use [`Self::queue_hotkey`] so its capture loop
    /// never waits for a child process.
    pub fn execute_hotkey(result: &HotkeyResult) -> Result<(), HotkeyError> {
        let mut command = Command::new(&result.command.program);
        configure_command_environment(&mut command, &result.command);
        command
            .args(&result.command.args)
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null());
        configure_process_group(&mut command);
        let mut child = command.spawn().map_err(HotkeyError::Spawn)?;
        let deadline = Instant::now() + Duration::from_millis(result.command.timeout_ms);
        let status = loop {
            match child.try_wait() {
                Ok(Some(status)) => break status,
                Ok(None) if Instant::now() < deadline => thread::sleep(Duration::from_millis(5)),
                Ok(None) => {
                    kill_process_group(&child);
                    let _ = child.wait();
                    return Err(HotkeyError::Timeout(result.command.timeout_ms));
                }
                Err(error) => {
                    kill_process_group(&child);
                    let _ = child.wait();
                    return Err(HotkeyError::Spawn(error));
                }
            }
        };

        // Kill process group to ensure any descendant processes are terminated
        kill_process_group(&child);

        if status.success() {
            Ok(())
        } else {
            Err(HotkeyError::Failed(status.to_string()))
        }
    }

    /// Process an event stream. A text event may contain multiple Unicode
    /// scalar values; matching is performed after each one.
    pub fn process(&mut self, event: InputEvent) -> Vec<ExpansionResult> {
        // A pending undo is valid only immediately after the expansion it
        // would revert, with no other event in between. `InputEvent::Key`
        // is exempt: it never touches the buffer or produces a result here
        // (see below), and is how the undo chord itself arrives -- clearing
        // on it would make undo impossible to ever trigger.
        if !matches!(event, InputEvent::Key(_)) {
            self.last_expansion = None;
        }
        match event {
            InputEvent::Key(_) => {
                self.input_generation = self.input_generation.wrapping_add(1);
                Vec::new()
            }
            InputEvent::Text(text) => {
                let mut results = Vec::new();
                let mut result_bytes = 0usize;
                if !self.is_capture_enabled() {
                    return results;
                }
                for character in text.chars() {
                    self.input_generation = self.input_generation.wrapping_add(1);
                    let pending = self.matcher.find_suffix(self.buffer.iter().rev().copied());
                    if let Some((index, length)) = pending {
                        if let Some(config_index) = self.matcher_indices.get(index).copied() {
                            let trigger = &self.config.expansion[config_index].trigger;
                            let match_mode = self.config.expansion[config_index].match_mode;
                            if !self.matcher.can_continue(trigger, character) {
                                let trailing_word_character = match_mode == MatchMode::WordBoundary
                                    && is_word_character(character);
                                if !trailing_word_character {
                                    if let Some(result) =
                                        self.take_match(config_index, length, Some(character))
                                    {
                                        let bytes = result
                                            .trigger
                                            .len()
                                            .saturating_add(result.insert.len());
                                        if results.len() >= MAX_RESULTS_PER_EVENT
                                            || result_bytes.saturating_add(bytes)
                                                > MAX_RESULT_BYTES_PER_EVENT
                                        {
                                            self.clear_buffer();
                                            break;
                                        }
                                        result_bytes = result_bytes.saturating_add(bytes);
                                        results.push(result);
                                    }
                                }
                            }
                        }
                    }
                    if results.len() >= MAX_RESULTS_PER_EVENT {
                        self.clear_buffer();
                        break;
                    }
                    self.buffer.push_back(character);
                    while self.buffer.len() > self.max_buffer_chars {
                        self.buffer.pop_front();
                        self.buffer_truncated = true;
                    }
                    if let Some((index, length)) =
                        self.matcher.find_suffix(self.buffer.iter().rev().copied())
                    {
                        let config_index = self.matcher_indices.get(index).copied();
                        let Some(config_index) = config_index else {
                            self.clear_buffer();
                            continue;
                        };
                        let (trigger, match_mode) = {
                            let expansion = &self.config.expansion[config_index];
                            (expansion.trigger.clone(), expansion.match_mode)
                        };
                        // The actually-typed suffix, which may be an
                        // uppercase or capitalized variant of `trigger` for
                        // a `propagate_case` expansion (see
                        // `ExpansionEngine::new`): `has_continuation` must
                        // be checked against what was typed, since that is
                        // the string actually present in the forward trie,
                        // not necessarily `trigger` itself.
                        let typed: String = {
                            let start = self.buffer.len().saturating_sub(length);
                            self.buffer.iter().skip(start).collect()
                        };
                        if self.matcher.has_continuation(&typed)
                            || match_mode == MatchMode::WordBoundary
                        {
                            continue;
                        }
                        if let Some(result) = self.take_match(config_index, length, None) {
                            let expansion_bytes = trigger.len().saturating_add(result.insert.len());
                            if result_bytes.saturating_add(expansion_bytes)
                                > MAX_RESULT_BYTES_PER_EVENT
                            {
                                self.clear_buffer();
                                break;
                            }
                            result_bytes = result_bytes.saturating_add(expansion_bytes);
                            results.push(result);
                        }
                        // Do not allow a replacement to combine with the
                        // next typed text and accidentally trigger again.
                        self.clear_buffer();
                    }
                }
                results
            }
            InputEvent::Delimiter(character) => {
                self.process(InputEvent::Text(character.to_string()))
            }
            InputEvent::Backspace => {
                self.input_generation = self.input_generation.wrapping_add(1);
                self.buffer.pop_back();
                Vec::new()
            }
            InputEvent::EndOfInput => {
                self.input_generation = self.input_generation.wrapping_add(1);
                let result = self
                    .matcher
                    .find_suffix(self.buffer.iter().rev().copied())
                    .and_then(|(index, length)| {
                        self.matcher_indices
                            .get(index)
                            .copied()
                            .and_then(|config_index| self.take_match(config_index, length, None))
                    });
                self.clear_buffer();
                result.into_iter().collect()
            }
            InputEvent::Reset => {
                self.input_generation = self.input_generation.wrapping_add(1);
                self.clear_buffer();
                Vec::new()
            }
            InputEvent::FocusChanged { sensitive } => {
                self.input_generation = self.input_generation.wrapping_add(1);
                self.sensitive_focus = sensitive;
                self.clear_buffer();
                Vec::new()
            }
            InputEvent::PauseChanged(paused) => {
                self.input_generation = self.input_generation.wrapping_add(1);
                self.user_paused = paused;
                self.clear_buffer();
                Vec::new()
            }
            InputEvent::WindowChanged(window) => {
                self.input_generation = self.input_generation.wrapping_add(1);
                // The text in the buffer belongs to the previously-focused
                // application. Text expansion state must be scoped to the
                // focused window, not to the desktop session. Even if
                // app_filter would correctly re-evaluate against the new
                // window, the physical characters in the buffer are from the
                // old application and must not be used to compute replacements
                // for the new one. This prevents cross-window trigger matches
                // that can cause unrelated text deletion.
                self.current_window = window;
                self.clear_buffer();
                Vec::new()
            }
        }
    }

    fn take_match(
        &mut self,
        config_index: usize,
        length: usize,
        terminating_char: Option<char>,
    ) -> Option<ExpansionResult> {
        if !self.match_allowed(config_index, length) {
            return None;
        }
        let trigger = self.config.expansion[config_index].trigger.clone();
        let propagate_case = self.config.expansion[config_index].propagate_case;
        // Read the actually-typed trigger text (which may be an uppercase
        // or capitalized variant registered in the matcher for this entry;
        // see `ExpansionEngine::new`) before it is popped off below. Needed
        // both for case propagation and as the text an undo restores.
        let typed: String = {
            let start = self.buffer.len().saturating_sub(length);
            self.buffer.iter().skip(start).collect()
        };
        let expansion = &self.config.expansion[config_index];
        let cached_command = expansion.command.as_ref().and_then(|command| {
            (command.cache_ms > 0)
                .then(|| self.command_cache[config_index].as_ref())
                .flatten()
                .filter(|entry| entry.expires_at > Instant::now())
                .map(|entry| entry.value.clone())
        });
        let (mut insert, cursor_offset) = if let Some(value) = cached_command {
            (value, None)
        } else if let (Some(runtime), Some(command)) =
            (self.async_commands.as_ref(), expansion.command.as_ref())
        {
            // Policy enforcement: block command execution if policy disables it
            if self.config.organization.disable_commands {
                return None;
            }

            let result = ExpansionResult {
                trigger,
                matched_text: typed,
                insert: String::new(),
                cursor_offset: None,
                reinsert_after: terminating_char.filter(|_| self.reinsert_terminators),
                command_backed: true,
            };
            let job = AsyncCommandJob::Expansion {
                config_index,
                generation: self.input_generation,
                command: command.clone(),
                result,
            };
            if runtime.try_send_command(job).is_err() {
                return None;
            }
            // Do not consume the trigger until the worker has accepted the
            // job. A saturated queue therefore cannot make input silently
            // disappear from the engine's state.
            for _ in 0..length {
                self.buffer.pop_back();
            }
            self.last_expansion = None;
            return None;
        } else {
            self.render_expansion(config_index).ok()?
        };
        if propagate_case {
            insert = apply_case_style(&typed, &insert);
        }
        for _ in 0..length {
            self.buffer.pop_back();
        }
        if cursor_offset.is_none() {
            self.last_expansion = Some((typed.clone(), insert.clone()));
        }
        Some(ExpansionResult {
            trigger,
            matched_text: typed,
            insert,
            cursor_offset,
            reinsert_after: terminating_char.filter(|_| self.reinsert_terminators),
            command_backed: false,
        })
    }

    /// Renders an expansion's text and, for a plain (non-command-backed)
    /// template containing a `{{cursor}}` marker, the number of characters
    /// from the end of the rendered text the cursor should land at.
    /// Command output is used verbatim -- it is not hand-authored per
    /// invocation the way a template is, so `{{cursor}}` is not recognized
    /// in it.
    fn render_expansion(&mut self, config_index: usize) -> Result<(String, Option<usize>), ()> {
        let expansion = &self.config.expansion[config_index];
        let Some(command) = &expansion.command else {
            return render_template_with_cursor(
                &expansion.replacement,
                &crate::TemplateContext::system(),
            )
            .map_err(|_| ());
        };
        if command.cache_ms > 0 {
            if let Some(entry) = self.command_cache[config_index].as_ref() {
                if entry.expires_at > Instant::now() {
                    return Ok((entry.value.clone(), None));
                }
            }
        }
        let value = run_command(command).map_err(|_| ())?;
        if command.cache_ms > 0 {
            self.command_cache[config_index] = Some(CommandCacheEntry {
                expires_at: Instant::now() + Duration::from_millis(command.cache_ms),
                value: value.clone(),
            });
        }
        Ok((value, None))
    }

    /// Resets the matcher buffer to a known boundary. Always use this
    /// instead of `self.buffer.clear()` directly: it also clears
    /// `buffer_truncated`, since a fresh boundary means whatever preceded it
    /// is no longer relevant to word-boundary checks.
    fn clear_buffer(&mut self) {
        self.buffer.clear();
        self.buffer_truncated = false;
    }

    fn match_allowed(&self, config_index: usize, length: usize) -> bool {
        let expansion = &self.config.expansion[config_index];
        if !self.app_filter_allows(expansion) {
            return false;
        }
        if expansion.match_mode != MatchMode::WordBoundary {
            return true;
        }
        match self.buffer.iter().rev().nth(length) {
            Some(character) => !is_word_character(*character),
            // A `None` here is ambiguous unless we know nothing was ever
            // evicted: it means either "this is genuinely the start of
            // input" (allow) or "a preceding character existed but was
            // truncated out of the buffer" (unknown -- fail closed).
            None => !self.buffer_truncated,
        }
    }

    /// An expansion with an empty `app_filter` matches everywhere. A
    /// non-empty filter requires a known focused window whose app id contains
    /// one of the filter substrings (case-insensitive, preferred) or whose
    /// title contains one (as a fallback when app_id is unavailable); if
    /// window tracking is unavailable, this fails closed rather than
    /// matching unconditionally.
    ///
    /// App ID matching is preferred because it's more reliable than window
    /// titles, which can be user-editable or transient.
    fn app_filter_allows(&self, expansion: &crate::ExpansionConfig) -> bool {
        if expansion.app_filter.is_empty() {
            return true;
        }
        let Some(window) = &self.current_window else {
            return false;
        };
        expansion.app_filter.iter().any(|filter| {
            let filter = filter.to_lowercase();
            // If app_id is available, ONLY match against it (never fall back to title).
            // Rationale: app_id is set by the compositor and reliable; title is
            // user-editable and can be spoofed to match sensitive filters.
            if let Some(app_id) = window.app_id.as_deref() {
                app_id.to_lowercase().contains(&filter)
            } else if self.config.organization.disable_title_matching {
                // Policy: disable_title_matching means no title fallback.
                // Fail closed: don't match without app_id (per CLAUDE.md conventions).
                false
            } else {
                // App ID unavailable but title matching allowed: fall back to title
                window
                    .title
                    .as_deref()
                    .is_some_and(|title| title.to_lowercase().contains(&filter))
            }
        })
    }

    /// Apply an expansion. Backends may perform the replacement atomically;
    /// simple backends use the safe erase-then-insert default.
    pub fn apply<I: TextInjector + ?Sized>(
        injector: &mut I,
        result: &ExpansionResult,
    ) -> Result<(), ExpansionError> {
        // Input capture is non-exclusive, so a character that completed a
        // delayed match has already reached the application. Replace that
        // character together with the trigger and append it to the replacement
        // in one backend operation. Use the text actually typed for exact
        // surrounding-text validation and case-propagated triggers.
        let erase = result.matched_text.clone();
        let mut insert = result.insert.clone();
        if let Some(character) = result.reinsert_after {
            insert.push(character);
        }
        injector.replace(&erase, &insert)?;
        // Best-effort: a `{{cursor}}` marker's placement failing (or being
        // unsupported by this backend) does not mean the expansion itself
        // failed, since the replacement text above was already inserted.
        let trailing_offset = usize::from(result.reinsert_after.is_some());
        if let Some(offset) = result
            .cursor_offset
            .map(|offset| offset.saturating_add(trailing_offset))
            .filter(|offset| *offset > 0)
        {
            let _ = injector.move_cursor_left(offset);
        }
        Ok(())
    }
}

fn is_word_character(character: char) -> bool {
    character.is_alphanumeric() || character == '_'
}

/// Recases `text` (a rendered replacement) to match the casing pattern of
/// `typed` (the trigger as the user actually typed it), for expansions with
/// `propagate_case` enabled. A single capitalized letter or a capitalized
/// word yields a capitalized replacement; two or more uppercase letters
/// yield a fully uppercased replacement; anything else (typed as
/// configured, or mixed case) leaves the replacement unchanged.
fn apply_case_style(typed: &str, text: &str) -> String {
    let letters: Vec<char> = typed
        .chars()
        .filter(|character| character.is_alphabetic())
        .collect();
    match letters.as_slice() {
        [] => text.to_owned(),
        [single] if single.is_uppercase() => capitalize_first_letter(text),
        letters if letters.iter().all(|character| character.is_uppercase()) => text.to_uppercase(),
        [first, ..] if first.is_uppercase() => capitalize_first_letter(text),
        _ => text.to_owned(),
    }
}

/// Why a command-backed expansion's configured program did not produce
/// usable output.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CommandError {
    /// The program could not be started at all (not found, not executable,
    /// permission denied, ...).
    SpawnFailed,
    /// The program did not exit within `command.timeout_ms` and was killed.
    Timeout,
    /// The process status could not be obtained after the program was started.
    WaitFailed(String),
    /// The program exited but reported failure.
    NonZeroExit(Option<i32>),
    /// Output exceeded the bounded size this engine will buffer.
    OutputTooLarge,
    /// Output was not valid UTF-8.
    InvalidUtf8,
    /// The output-reading thread did not report back in time (should not
    /// happen once the process itself has exited; treated as a distinct
    /// case rather than folded into `Timeout` since it points at a bug in
    /// the reader thread, not a slow command).
    OutputChannelLost,
}

impl std::fmt::Display for CommandError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            CommandError::SpawnFailed => write!(f, "could not start the program"),
            CommandError::Timeout => write!(f, "timed out before it produced output"),
            CommandError::WaitFailed(error) => {
                write!(f, "failed while obtaining process status: {error}")
            }
            CommandError::NonZeroExit(Some(code)) => write!(f, "exited with status {code}"),
            CommandError::NonZeroExit(None) => write!(f, "was terminated by a signal"),
            CommandError::OutputTooLarge => write!(
                f,
                "produced more than {} bytes of output",
                MAX_COMMAND_OUTPUT_BYTES
            ),
            CommandError::InvalidUtf8 => write!(f, "produced output that was not valid UTF-8"),
            CommandError::OutputChannelLost => write!(f, "output could not be read back"),
        }
    }
}

impl std::error::Error for CommandError {}

/// Runs a command-backed expansion's configured program to completion and
/// returns its trimmed stdout. Public so the GUI/CLI can invoke it directly
/// for an explicit, user-initiated "run once" preview -- callers must never
/// invoke this from a rendering/repaint loop, since it spawns a real process
/// with real side effects on every call.
pub fn run_command(command: &CommandConfig) -> Result<String, CommandError> {
    let mut process = Command::new(&command.program);
    configure_command_environment(&mut process, command);
    process
        .args(&command.args)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::null());
    configure_process_group(&mut process);
    let mut child = process.spawn().map_err(|_| CommandError::SpawnFailed)?;
    let stdout = child.stdout.take().ok_or(CommandError::SpawnFailed)?;
    let (sender, receiver) = mpsc::sync_channel(1);
    thread::spawn(move || {
        let mut bytes = Vec::new();
        let result = stdout
            .take((MAX_COMMAND_OUTPUT_BYTES + 1) as u64)
            .read_to_end(&mut bytes)
            .map(|_| bytes);
        let _ = sender.send(result);
    });

    let deadline = Instant::now() + Duration::from_millis(command.timeout_ms);
    let status = loop {
        match child.try_wait() {
            Ok(Some(status)) => break status,
            Ok(None) if Instant::now() < deadline => thread::sleep(Duration::from_millis(5)),
            Ok(None) => {
                kill_process_group(&child);
                let _ = child.wait();
                return Err(CommandError::Timeout);
            }
            Err(error) => {
                kill_process_group(&child);
                let _ = child.wait();
                return Err(CommandError::WaitFailed(error.to_string()));
            }
        }
    };

    // Kill process group to ensure any descendant processes are terminated
    kill_process_group(&child);

    if !status.success() {
        return Err(CommandError::NonZeroExit(status.code()));
    }
    let bytes = receiver
        .recv_timeout(Duration::from_millis(100))
        .map_err(|_| CommandError::OutputChannelLost)?
        .map_err(|_| CommandError::OutputChannelLost)?;
    if bytes.len() > MAX_COMMAND_OUTPUT_BYTES {
        return Err(CommandError::OutputTooLarge);
    }
    let output = String::from_utf8(bytes).map_err(|_| CommandError::InvalidUtf8)?;
    Ok(output.trim_end_matches(['\r', '\n']).to_owned())
}

fn configure_command_environment(process: &mut Command, command: &CommandConfig) {
    if command.environment == CommandEnvironment::Inherit {
        return;
    }

    process.env_clear();
    for name in ["HOME", "USER", "PATH", "LANG"] {
        if let Some(value) = std::env::var_os(name) {
            process.env(name, value);
        }
    }
    for name in &command.pass_env {
        if let Some(value) = std::env::var_os(name) {
            process.env(name, value);
        }
    }
}

#[cfg(unix)]
fn configure_process_group(command: &mut Command) {
    unsafe {
        command.pre_exec(|| {
            if libc::setpgid(0, 0) == -1 {
                return Err(std::io::Error::last_os_error());
            }
            Ok(())
        });
    }
}

#[cfg(not(unix))]
fn configure_process_group(_command: &mut Command) {}

#[cfg(unix)]
fn kill_process_group(child: &std::process::Child) {
    if let Ok(pid) = libc::pid_t::try_from(child.id()) {
        unsafe {
            libc::kill(-pid, libc::SIGKILL);
        }
    }
}

#[cfg(not(unix))]
fn kill_process_group(child: &mut std::process::Child) {
    let _ = child.kill();
}

