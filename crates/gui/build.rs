use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

const LANGUAGES: [(&str, &str); 3] = [("en", "English"), ("de", "German"), ("id", "Indonesian")];

fn main() {
    wayexpand_build_info::emit();
    generate_locale_strings();
}

/// Read `locales/{en,de,id}.toml` and generate one method on `Strings` per
/// key. A key whose placeholders are all names (`{count}`, `{app_id}`) gets a
/// method taking those values, in the order English first uses them, and
/// returning the filled `String`; translations may reorder named
/// placeholders. Any other key returns its `&'static str` template.
///
/// The build fails when a language lacks a key, has an extra one, or uses
/// different placeholders than English (the same names, or for unnamed
/// placeholders the same sequence), so a translation can never silently fall
/// back or drop a value.
fn generate_locale_strings() {
    let dir = Path::new("locales");
    println!("cargo:rerun-if-changed=locales");
    let mut tables = Vec::new();
    for (code, _) in LANGUAGES {
        let path = dir.join(format!("{code}.toml"));
        println!("cargo:rerun-if-changed={}", path.display());
        let source = std::fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("reading {}: {error}", path.display()));
        let value: toml::Table = source
            .parse()
            .unwrap_or_else(|error| panic!("parsing {}: {error}", path.display()));
        tables.push(flatten(code, &value));
    }
    let english = &tables[0];
    let mut problems = Vec::new();
    for ((code, _), table) in LANGUAGES.iter().zip(&tables).skip(1) {
        for key in english.keys().filter(|key| !table.contains_key(*key)) {
            problems.push(format!("{code}.toml is missing `{key}`"));
        }
        for key in table.keys().filter(|key| !english.contains_key(*key)) {
            problems.push(format!("{code}.toml has `{key}`, which en.toml does not"));
        }
        for (key, text) in table {
            if let Some(source) = english.get(key) {
                let differs = match named_placeholders(source) {
                    Some(mut names) => {
                        names.sort_unstable();
                        let mut other = named_placeholders(text).unwrap_or_default();
                        other.sort_unstable();
                        other.dedup();
                        names != other
                    }
                    None => placeholders(source) != placeholders(text),
                };
                if differs {
                    problems.push(format!(
                        "{code}.toml `{key}` uses placeholders {:?}; en.toml uses {:?}",
                        placeholders(text),
                        placeholders(source)
                    ));
                }
            }
        }
    }
    assert!(
        problems.is_empty(),
        "GUI locale files disagree:\n  {}",
        problems.join("\n  ")
    );

    let mut code = String::from(
        "// Generated by build.rs from crates/gui/locales/*.toml. Do not edit.\n\
         impl crate::lang::Strings {\n",
    );
    for key in english.keys() {
        let names = named_placeholders(&english[key]);
        match &names {
            Some(names) => {
                let params: Vec<String> = names
                    .iter()
                    .map(|name| format!(", {name}: impl std::fmt::Display"))
                    .collect();
                let _ = writeln!(
                    code,
                    "    pub fn {key}(&self{}) -> String {{\n        let template = match self.lang {{",
                    params.concat()
                );
            }
            None => {
                let _ = writeln!(
                    code,
                    "    pub fn {key}(&self) -> &'static str {{\n        match self.lang {{"
                );
            }
        }
        for ((_, variant), table) in LANGUAGES.iter().zip(&tables) {
            let _ = writeln!(
                code,
                "            crate::lang::Language::{variant} => {:?},",
                table[key]
            );
        }
        match &names {
            Some(names) => {
                let values: Vec<String> = names
                    .iter()
                    .map(|name| format!("({name:?}, &{name} as &dyn std::fmt::Display)"))
                    .collect();
                let _ = writeln!(
                    code,
                    "        }};\n        crate::lang::fill_named(template, &[{}])\n    }}",
                    values.join(", ")
                );
            }
            None => code.push_str("        }\n    }\n"),
        }
    }
    code.push_str("}\n");
    let out =
        Path::new(&std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("locale_strings.rs");
    std::fs::write(&out, code).expect("writing generated locale strings");
}

/// Tables only group keys for readers; keys are unique across the file.
fn flatten(code: &str, table: &toml::Table) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    for (section, value) in table {
        let toml::Value::Table(entries) = value else {
            panic!("{code}.toml: `{section}` must be a [section] of strings");
        };
        for (key, text) in entries {
            let toml::Value::String(text) = text else {
                panic!("{code}.toml: `{section}.{key}` must be a string");
            };
            assert!(
                out.insert(key.clone(), text.clone()).is_none(),
                "{code}.toml: `{key}` appears in more than one section"
            );
        }
    }
    out
}

/// The distinct placeholder names of a template, in order of first use, when
/// it has placeholders and every one is a Rust identifier; otherwise `None`.
fn named_placeholders(text: &str) -> Option<Vec<&str>> {
    let found = placeholders(text);
    if found.is_empty() {
        return None;
    }
    let mut names = Vec::new();
    for holder in found {
        let name = &holder[1..holder.len() - 1];
        let identifier = name
            .chars()
            .next()
            .is_some_and(|first| first.is_ascii_lowercase() || first == '_')
            && name
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
        if !identifier {
            return None;
        }
        if !names.contains(&name) {
            names.push(name);
        }
    }
    Some(names)
}

/// The `{...}` placeholders of a template, in order.
fn placeholders(text: &str) -> Vec<&str> {
    let mut found = Vec::new();
    let mut rest = text;
    while let Some(start) = rest.find('{') {
        let Some(end) = rest[start..].find('}') else {
            break;
        };
        found.push(&rest[start..start + end + 1]);
        rest = &rest[start + end + 1..];
    }
    found
}
