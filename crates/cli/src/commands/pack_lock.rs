//! `packs.lock`: the exact pack versions and contents a machine should have.
//!
//! `pack lock` records the installed packs; `pack lock --check` reports drift
//! (missing, extra, other version, or locally edited content);
//! `pack outdated` and `pack update` move installed packs to newer catalog
//! versions; `pack sync` installs exactly what a (team) lockfile pins. Every
//! installation goes through the same trust gate as `pack install`, and the
//! content fingerprint ties a locked entry to the bytes that were reviewed.

use super::config::{
    ensure_pack_id, installed_pack_root, scan_pack_catalog, sync_directory,
    validate_pack_fingerprint,
};
use super::pack_trust::PackTrust;
use crate::*;
use serde::{Deserialize, Serialize};
use std::io::{Read, Write};
use std::os::unix::fs::OpenOptionsExt;

const LOCK_FORMAT_VERSION: u32 = 1;
const LOCK_FILE_NAME: &str = "packs.lock";
const MAX_LOCK_BYTES: u64 = 1024 * 1024;
const MAX_LOCKED_PACKS: usize = 512;
const LOCK_HEADER: &str = "# Generated by `wayexpand pack lock`. Commit it next to your pack catalog\n# and run `wayexpand pack sync <catalog> --lock packs.lock` on each machine.\n";

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub(crate) struct PackLock {
    format_version: u32,
    #[serde(default, rename = "pack")]
    packs: Vec<LockedPack>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub(crate) struct LockedPack {
    id: String,
    version: String,
    fingerprint: String,
}

/// One installed pack as the lockfile sees it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum InstalledPack {
    Valid {
        id: String,
        version: String,
        fingerprint: String,
    },
    Invalid {
        id: String,
    },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub(crate) enum Drift {
    /// Locked but not installed.
    Missing { id: String, version: String },
    /// Installed but not locked.
    Extra { id: String, version: Option<String> },
    /// Installed at another version than the lock pins.
    Version {
        id: String,
        locked: String,
        installed: String,
    },
    /// Same version, different content (usually a local edit).
    Modified { id: String, version: String },
    /// Installed but does not validate.
    Invalid { id: String },
}

impl std::fmt::Display for Drift {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Drift::Missing { id, version } => {
                write!(formatter, "{id} {version}: locked but not installed")
            }
            Drift::Extra { id, version } => write!(
                formatter,
                "{id} {}: installed but not locked",
                version.as_deref().unwrap_or("(invalid)")
            ),
            Drift::Version {
                id,
                locked,
                installed,
            } => write!(
                formatter,
                "{id}: lock pins {locked}, {installed} is installed"
            ),
            Drift::Modified { id, version } => write!(
                formatter,
                "{id} {version}: installed content differs from the locked fingerprint"
            ),
            Drift::Invalid { id } => write!(formatter, "{id}: installed pack does not validate"),
        }
    }
}

impl PackLock {
    fn validate(&self) -> Result<()> {
        if self.format_version != LOCK_FORMAT_VERSION {
            bail!(
                "pack lockfile format_version {} is unsupported",
                self.format_version
            );
        }
        if self.packs.len() > MAX_LOCKED_PACKS {
            bail!("pack lockfile pins more than {MAX_LOCKED_PACKS} packs");
        }
        let mut seen = std::collections::BTreeSet::new();
        for pack in &self.packs {
            ensure_pack_id(&pack.id)?;
            if !seen.insert(pack.id.as_str()) {
                bail!("pack lockfile pins {} more than once", pack.id);
            }
            semver::Version::parse(&pack.version).map_err(|_| {
                config_error(format!(
                    "pack lockfile has an invalid version for {}",
                    pack.id
                ))
            })?;
            validate_pack_fingerprint(&pack.fingerprint)?;
        }
        Ok(())
    }

    fn from_installed(installed: &[InstalledPack]) -> Result<Self> {
        let mut packs = Vec::new();
        for pack in installed {
            match pack {
                InstalledPack::Valid {
                    id,
                    version,
                    fingerprint,
                } => packs.push(LockedPack {
                    id: id.clone(),
                    version: version.clone(),
                    fingerprint: fingerprint.clone(),
                }),
                InstalledPack::Invalid { id } => {
                    bail!("installed pack {id} does not validate; fix or remove it before locking")
                }
            }
        }
        packs.sort_by(|left, right| left.id.cmp(&right.id));
        Ok(Self {
            format_version: LOCK_FORMAT_VERSION,
            packs,
        })
    }

    pub(crate) fn read(path: &Path) -> Result<Self> {
        let file = std::fs::File::open(path).map_err(|error| {
            config_error(format!(
                "could not open pack lockfile {}: {error}",
                path.display()
            ))
        })?;
        let mut source = String::new();
        file.take(MAX_LOCK_BYTES + 1)
            .read_to_string(&mut source)
            .map_err(|error| config_error(format!("could not read pack lockfile: {error}")))?;
        if source.len() as u64 > MAX_LOCK_BYTES {
            bail!("pack lockfile exceeds {MAX_LOCK_BYTES} bytes");
        }
        let lock: Self = toml::from_str(&source)
            .map_err(|error| config_error(format!("pack lockfile is invalid: {error}")))?;
        lock.validate()?;
        Ok(lock)
    }

    /// Replace `path` atomically: a reader sees the old or the new lock.
    pub(crate) fn write(&self, path: &Path) -> Result<()> {
        self.validate()?;
        let parent = path
            .parent()
            .filter(|parent| !parent.as_os_str().is_empty())
            .unwrap_or_else(|| Path::new("."));
        let file_name = path
            .file_name()
            .ok_or_else(|| usage_error("pack lockfile path has no file name"))?;
        let temporary = parent.join(format!(
            ".{}.{}.tmp",
            file_name.to_string_lossy(),
            std::process::id()
        ));
        let body = format!("{LOCK_HEADER}{}", toml::to_string_pretty(self)?);
        let result = (|| -> Result<()> {
            let mut file = std::fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .mode(0o644)
                .open(&temporary)
                .map_err(|error| {
                    config_error(format!("could not create pack lockfile: {error}"))
                })?;
            file.write_all(body.as_bytes())?;
            file.sync_all()?;
            std::fs::rename(&temporary, path).map_err(|error| {
                config_error(format!("could not replace pack lockfile: {error}"))
            })?;
            sync_directory(parent)
        })();
        if result.is_err() {
            let _ = std::fs::remove_file(&temporary);
        }
        result
    }
}

pub(crate) fn default_lock_path() -> Result<PathBuf> {
    let root = installed_pack_root()?;
    let parent = root
        .parent()
        .ok_or_else(|| config_error("local pack directory has no parent"))?;
    Ok(parent.join(LOCK_FILE_NAME))
}

pub(crate) fn installed_packs_at(root: &Path) -> Result<Vec<InstalledPack>> {
    let entries = match std::fs::read_dir(root) {
        Ok(entries) => entries,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(error) => return Err(config_error(format!("could not list local packs: {error}"))),
    };
    let mut packs = Vec::new();
    for entry in entries {
        let entry =
            entry.map_err(|error| config_error(format!("could not list local packs: {error}")))?;
        let metadata = std::fs::symlink_metadata(entry.path())
            .map_err(|error| config_error(format!("could not inspect local pack: {error}")))?;
        if !metadata.file_type().is_dir() {
            continue;
        }
        let name = entry.file_name().to_string_lossy().into_owned();
        packs.push(match wayexpand_core::inspect_pack(entry.path()) {
            Ok(inspection) if inspection.manifest.id == name => InstalledPack::Valid {
                id: inspection.manifest.id,
                version: inspection.manifest.version,
                fingerprint: inspection.fingerprint,
            },
            _ => InstalledPack::Invalid { id: name },
        });
    }
    packs.sort_by(|left, right| installed_id(left).cmp(installed_id(right)));
    Ok(packs)
}

fn installed_id(pack: &InstalledPack) -> &str {
    match pack {
        InstalledPack::Valid { id, .. } | InstalledPack::Invalid { id } => id,
    }
}

pub(crate) fn drift(lock: &PackLock, installed: &[InstalledPack]) -> Vec<Drift> {
    let mut drift = Vec::new();
    for locked in &lock.packs {
        match installed
            .iter()
            .find(|pack| installed_id(pack) == locked.id)
        {
            None => drift.push(Drift::Missing {
                id: locked.id.clone(),
                version: locked.version.clone(),
            }),
            Some(InstalledPack::Invalid { id }) => drift.push(Drift::Invalid { id: id.clone() }),
            Some(InstalledPack::Valid {
                version,
                fingerprint,
                ..
            }) => {
                if *version != locked.version {
                    drift.push(Drift::Version {
                        id: locked.id.clone(),
                        locked: locked.version.clone(),
                        installed: version.clone(),
                    });
                } else if *fingerprint != locked.fingerprint {
                    drift.push(Drift::Modified {
                        id: locked.id.clone(),
                        version: version.clone(),
                    });
                }
            }
        }
    }
    for pack in installed {
        if !lock
            .packs
            .iter()
            .any(|locked| locked.id == installed_id(pack))
        {
            drift.push(Drift::Extra {
                id: installed_id(pack).to_owned(),
                version: match pack {
                    InstalledPack::Valid { version, .. } => Some(version.clone()),
                    InstalledPack::Invalid { .. } => None,
                },
            });
        }
    }
    drift
}

/// Keep an existing default lockfile in step after the CLI changed the
/// installed set. A missing lockfile stays missing: locking is opt-in.
pub(crate) fn refresh_default_lock() {
    let Ok(path) = default_lock_path() else {
        return;
    };
    if std::fs::symlink_metadata(&path).is_err() {
        return;
    }
    let refreshed = installed_pack_root()
        .and_then(|root| installed_packs_at(&root))
        .and_then(|installed| PackLock::from_installed(&installed))
        .and_then(|lock| lock.write(&path));
    match refreshed {
        Ok(()) => println!("updated {}", path.display()),
        Err(error) => eprintln!(
            "warning: {} was not updated ({error}); run `wayexpand pack lock` after fixing it",
            path.display()
        ),
    }
}

/// `wayexpand pack lock [--check] [--lock FILE] [--json]`
pub(crate) fn lock_command(lock_path: Option<String>, check: bool, json: bool) -> Result<()> {
    let path = match lock_path {
        Some(path) => PathBuf::from(path),
        None => default_lock_path()?,
    };
    let installed = installed_packs_at(&installed_pack_root()?)?;
    if !check {
        if json {
            usage_bail!("--json is only supported by `pack lock --check`");
        }
        let lock = PackLock::from_installed(&installed)?;
        lock.write(&path)?;
        println!("locked {} pack(s) in {}", lock.packs.len(), path.display());
        return Ok(());
    }
    let lock = PackLock::read(&path)?;
    let drift = drift(&lock, &installed);
    if json {
        println!(
            "{}",
            serde_json::json!({
                "lockfile": path.display().to_string(),
                "in_sync": drift.is_empty(),
                "drift": drift,
            })
        );
    } else if drift.is_empty() {
        println!(
            "installed packs match {} ({} pack(s))",
            path.display(),
            lock.packs.len()
        );
    } else {
        for item in &drift {
            println!("{item}");
        }
    }
    if !drift.is_empty() {
        return Err(config_error(format!(
            "{} pack(s) differ from {}; run `wayexpand pack sync <catalog> --lock {}` to restore the locked set",
            drift.len(),
            path.display(),
            path.display()
        )));
    }
    Ok(())
}

/// The newest catalog version of each installed pack that is newer than
/// the installed one.
fn newest_candidates<'a>(
    scan: &'a super::config::CatalogScan,
    installed_id: &str,
    installed_version: &semver::Version,
) -> Option<&'a (PathBuf, wayexpand_core::PackInspection)> {
    scan.packs
        .iter()
        .filter(|(_, inspection)| inspection.manifest.id == installed_id)
        .filter_map(|candidate| {
            semver::Version::parse(&candidate.1.manifest.version)
                .ok()
                .filter(|version| version > installed_version)
                .map(|version| (version, candidate))
        })
        .max_by(|left, right| left.0.cmp(&right.0))
        .map(|(_, candidate)| candidate)
}

/// `wayexpand pack outdated <catalog> [--json] [--signers FILE]`
pub(crate) fn outdated_command(
    catalog: &Path,
    signers_override: Option<String>,
    json: bool,
) -> Result<()> {
    let trust = PackTrust::load(signers_override)?;
    let scan = scan_pack_catalog(catalog)?;
    let root = installed_pack_root()?;
    let mut updates = Vec::new();
    for pack in installed_packs_at(&root)? {
        let InstalledPack::Valid { id, version, .. } = pack else {
            continue;
        };
        let Ok(installed_version) = semver::Version::parse(&version) else {
            continue;
        };
        let Some((path, candidate)) = newest_candidates(&scan, &id, &installed_version) else {
            continue;
        };
        let current = wayexpand_core::inspect_pack(root.join(&id)).ok();
        updates.push(serde_json::json!({
            "id": id,
            "installed": version,
            "available": candidate.manifest.version,
            "path": path.strip_prefix(&scan.root).unwrap_or(path).display().to_string(),
            "source": path.display().to_string(),
            "fingerprint": candidate.fingerprint,
            "signature": trust.describe_signature(path),
            "commands": {
                "installed": current.as_ref().map(|current| current.command_count),
                "available": candidate.command_count,
            },
            "hotkeys": {
                "installed": current.as_ref().map(|current| current.hotkey_count),
                "available": candidate.hotkey_count,
            },
            "required_capabilities": candidate.required_capabilities,
        }));
    }
    if json {
        println!(
            "{}",
            serde_json::json!({ "updates": updates, "invalid_candidates": scan.invalid })
        );
        return Ok(());
    }
    if updates.is_empty() {
        println!(
            "All installed packs are up to date with {}",
            scan.root.display()
        );
    }
    for update in &updates {
        let signature = &update["signature"];
        println!(
            "{} {} -> {} [{}]",
            update["id"].as_str().unwrap_or_default(),
            update["installed"].as_str().unwrap_or_default(),
            update["available"].as_str().unwrap_or_default(),
            match signature["state"].as_str() {
                Some("verified") => format!(
                    "signed by {}",
                    signature["signer"].as_str().unwrap_or("unknown signer")
                ),
                Some(state) => state.replace('_', " "),
                None => "signature unknown".into(),
            }
        );
        if update["commands"]["available"] != update["commands"]["installed"]
            || update["hotkeys"]["available"] != update["hotkeys"]["installed"]
        {
            println!(
                "  actions change: commands {} -> {}, hotkeys {} -> {}",
                update["commands"]["installed"],
                update["commands"]["available"],
                update["hotkeys"]["installed"],
                update["hotkeys"]["available"]
            );
        }
    }
    for update in &updates {
        println!(
            "review: wayexpand pack diff {} {}\n  fingerprint: {}",
            update["id"].as_str().unwrap_or_default(),
            update["source"].as_str().unwrap_or_default(),
            update["fingerprint"].as_str().unwrap_or_default()
        );
    }
    if !updates.is_empty() {
        println!(
            "Then run `wayexpand pack update <catalog> <id> --expected-fingerprint <sha256>`."
        );
    }
    Ok(())
}

/// `wayexpand pack update <catalog> <id> [--expected-fingerprint SHA256]
/// [--allow-actions] [--signers FILE]`
pub(crate) fn update_command(
    catalog: &Path,
    id: &str,
    expected_fingerprint: Option<&str>,
    allow_actions: bool,
    signers_override: Option<String>,
) -> Result<()> {
    ensure_pack_id(id)?;
    let trust = PackTrust::load(signers_override)?;
    let root = installed_pack_root()?;
    let current = wayexpand_core::inspect_pack(root.join(id)).map_err(|error| {
        config_error(format!(
            "pack {id} is not installed or does not validate: {error}"
        ))
    })?;
    let installed_version = semver::Version::parse(&current.manifest.version)
        .map_err(|error| config_error(format!("installed pack has invalid version: {error}")))?;
    let scan = scan_pack_catalog(catalog)?;
    let Some((path, candidate)) = newest_candidates(&scan, id, &installed_version) else {
        println!(
            "{id} {} is already the newest version in {}",
            current.manifest.version,
            scan.root.display()
        );
        return Ok(());
    };
    if expected_fingerprint.is_some_and(|fingerprint| fingerprint != candidate.fingerprint) {
        bail!("pack contents changed since review; review the updated pack before installing");
    }
    let (installed, signer) = trust.install(path, candidate, true, false, allow_actions)?;
    println!(
        "updated {id} {} -> {} at {}{}",
        current.manifest.version,
        candidate.manifest.version,
        installed.display(),
        if signer.is_some() {
            " (signature verified)"
        } else {
            " (signature not verified)"
        }
    );
    refresh_default_lock();
    let _ = control_operation(wayexpand_core::DaemonOperation::Reload);
    Ok(())
}

/// `wayexpand pack sync <catalog> [--lock FILE] [--allow-actions]
/// [--signers FILE]`: install exactly the locked versions. Every entry is
/// found, verified and admitted before the first one is installed.
pub(crate) fn sync_command(
    catalog: &Path,
    lock_path: Option<String>,
    allow_actions: bool,
    signers_override: Option<String>,
) -> Result<()> {
    let path = match lock_path {
        Some(path) => PathBuf::from(path),
        None => default_lock_path()?,
    };
    let lock = PackLock::read(&path)?;
    let trust = PackTrust::load(signers_override)?;
    let root = installed_pack_root()?;
    let installed = installed_packs_at(&root)?;
    let scan = scan_pack_catalog(catalog)?;
    let mut planned = Vec::new();
    for locked in &lock.packs {
        let in_place = installed.iter().any(|pack| {
            matches!(pack, InstalledPack::Valid { id, fingerprint, .. }
                if *id == locked.id && *fingerprint == locked.fingerprint)
        });
        if in_place {
            continue;
        }
        let Some((source, inspection)) = scan.packs.iter().find(|(_, inspection)| {
            inspection.manifest.id == locked.id
                && inspection.manifest.version == locked.version
                && inspection.fingerprint == locked.fingerprint
        }) else {
            bail!(
                "{} has no pack {} {} with the locked fingerprint; nothing was installed",
                scan.root.display(),
                locked.id,
                locked.version
            );
        };
        trust.verify(source)?;
        trust.admit(inspection, allow_actions)?;
        let replace = installed.iter().any(|pack| installed_id(pack) == locked.id);
        planned.push((source, inspection, replace));
    }
    for (source, inspection, replace) in &planned {
        let (installed_path, _) =
            trust.install(source, inspection, *replace, true, allow_actions)?;
        println!(
            "installed {} {} at {}",
            inspection.manifest.id,
            inspection.manifest.version,
            installed_path.display()
        );
    }
    let extras: Vec<_> = installed
        .iter()
        .map(installed_id)
        .filter(|id| !lock.packs.iter().any(|locked| locked.id == *id))
        .collect();
    if !extras.is_empty() {
        println!(
            "not in the lockfile (left installed): {}",
            extras.join(", ")
        );
    }
    if planned.is_empty() {
        println!("installed packs already match {}", path.display());
    } else {
        if default_lock_path().ok().as_deref() != Some(path.as_path()) {
            refresh_default_lock();
        }
        let _ = control_operation(wayexpand_core::DaemonOperation::Reload);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fingerprint(byte: char) -> String {
        byte.to_string().repeat(64)
    }

    fn valid(id: &str, version: &str, print: char) -> InstalledPack {
        InstalledPack::Valid {
            id: id.into(),
            version: version.into(),
            fingerprint: fingerprint(print),
        }
    }

    fn locked(id: &str, version: &str, print: char) -> LockedPack {
        LockedPack {
            id: id.into(),
            version: version.into(),
            fingerprint: fingerprint(print),
        }
    }

    #[test]
    fn drift_reports_every_difference_from_the_lock() {
        let lock = PackLock {
            format_version: 1,
            packs: vec![
                locked("same", "1.0.0", 'a'),
                locked("edited", "1.0.0", 'b'),
                locked("moved", "1.0.0", 'c'),
                locked("gone", "2.0.0", 'd'),
                locked("broken", "1.0.0", 'e'),
            ],
        };
        let installed = vec![
            valid("same", "1.0.0", 'a'),
            valid("edited", "1.0.0", 'f'),
            valid("moved", "1.1.0", 'c'),
            InstalledPack::Invalid {
                id: "broken".into(),
            },
            valid("new", "0.1.0", '0'),
        ];
        assert_eq!(
            drift(&lock, &installed),
            vec![
                Drift::Modified {
                    id: "edited".into(),
                    version: "1.0.0".into()
                },
                Drift::Version {
                    id: "moved".into(),
                    locked: "1.0.0".into(),
                    installed: "1.1.0".into()
                },
                Drift::Missing {
                    id: "gone".into(),
                    version: "2.0.0".into()
                },
                Drift::Invalid {
                    id: "broken".into()
                },
                Drift::Extra {
                    id: "new".into(),
                    version: Some("0.1.0".into())
                },
            ]
        );
        assert!(drift(&lock, &[]).len() == 5);
    }

    #[test]
    fn lockfiles_round_trip_and_reject_unsafe_entries() {
        let directory = std::env::temp_dir().join(format!(
            "wayexpand-pack-lock-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::create_dir(&directory).unwrap();
        let path = directory.join("packs.lock");
        let lock =
            PackLock::from_installed(&[valid("b.pack", "1.0.0", 'b'), valid("a", "2.1.0", 'a')])
                .unwrap();
        assert_eq!(lock.packs[0].id, "a", "entries are sorted for stable diffs");
        lock.write(&path).unwrap();
        assert_eq!(PackLock::read(&path).unwrap(), lock);
        assert!(std::fs::read_to_string(&path)
            .unwrap()
            .starts_with("# Generated"));

        for body in [
            "format_version = 2\n",
            "format_version = 1\n[[pack]]\nid = \"../x\"\nversion = \"1.0.0\"\nfingerprint = \"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\"\n",
            "format_version = 1\n[[pack]]\nid = \"a\"\nversion = \"one\"\nfingerprint = \"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\"\n",
            "format_version = 1\n[[pack]]\nid = \"a\"\nversion = \"1.0.0\"\nfingerprint = \"AAAA\"\n",
            "format_version = 1\nextra = true\n",
        ] {
            std::fs::write(&path, body).unwrap();
            assert!(PackLock::read(&path).is_err(), "{body}");
        }
        let duplicate = format!(
            "format_version = 1\n[[pack]]\nid = \"a\"\nversion = \"1.0.0\"\nfingerprint = \"{0}\"\n[[pack]]\nid = \"a\"\nversion = \"1.0.0\"\nfingerprint = \"{0}\"\n",
            fingerprint('a')
        );
        std::fs::write(&path, duplicate).unwrap();
        assert!(PackLock::read(&path).is_err());
        assert!(PackLock::from_installed(&[InstalledPack::Invalid { id: "x".into() }]).is_err());
        std::fs::remove_dir_all(directory).unwrap();
    }
}
